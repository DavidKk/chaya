'use strict'

const assert = require('node:assert/strict')
const { createHash } = require('node:crypto')
const fs = require('node:fs/promises')
const path = require('node:path')

// Both paths use the actual host and model service. This tool never chooses an action for either path.
exports.runHostBenchmark = async function ({ window, evaluate, waitFor, delay, output, origin, bundle, config, troopId, fixture, save, mark }) {
  const prompt = '帮我完成当前这场战斗，战斗结束后停止，不要离开地图。'
  const checkpoint = await evaluate('__companionHostSmoke.checkpoint()')
  const checkpointSha256 = createHash('sha256').update(checkpoint).digest('hex')
  await fs.writeFile(path.join(output, 'battle-checkpoint.json'), checkpoint)
  const attempts = []
  const mapReady =
    "SceneManager._scene?.constructor.name === 'Scene_Map' && (SceneManager._scene.isStarted?.() ?? SceneManager._sceneStarted) && !SceneManager._scene.isBusy() && !SceneManager.isSceneChanging() && !$gamePlayer.isTransferring()"
  const order = ['legacy', 'local', 'local', 'legacy']
  for (const [index, mode] of order.entries()) {
    if (index) {
      await evaluate('__companionHostSmoke.dispose()')
      await window.loadURL(origin)
      await evaluate("Object.defineProperty(document, 'hasFocus', { value: () => true, configurable: true }); true")
      await waitFor("globalThis.SceneManager?._scene?.constructor.name === 'Scene_Title' && DataManager.isDatabaseLoaded()", 60000)
      await evaluate(bundle + '\n;true')
      await evaluate(`__companionSmoke.prepare('host',${troopId},undefined,${JSON.stringify(fixture)})`)
      await waitFor(mapReady)
      await evaluate(`__companionHostSmoke.boot(${JSON.stringify(config)})`)
    }
    const restored = await evaluate(`__companionHostSmoke.restoreCheckpoint(${JSON.stringify(checkpoint)})`)
    // Compare synchronously, before map animation counters advance. The companion's save-time stamp is regenerated by its save hook.
    const gameplay = (contents) => {
      const value = JSON.parse(contents)
      delete value._chayaCompanion
      return value
    }
    assert.deepEqual(gameplay(restored), gameplay(checkpoint), 'Every path restores identical gameplay save contents')
    await waitFor(mapReady)
    const runId = `${index + 1}-${mode}`
    const before = await save(`benchmark-${runId}-before`)
    const traceStart = before.engine.trace.length
    await evaluate(`__companionHostSmoke.battle(${troopId})`)
    await waitFor("SceneManager._scene?.constructor.name === 'Scene_Battle' && !!SceneManager._scene._actorCommandWindow")
    const startedAt = Date.now()
    let task, route, startError
    try {
      if (mode === 'legacy') task = await evaluate(`__companionHostSmoke.legacy(${JSON.stringify(prompt)})`)
      else {
        route = await evaluate(`__companionHostSmoke.route(${JSON.stringify(prompt)})`)
        assert.equal(route.kind, 'control', JSON.stringify(route))
        assert.equal(route.lifetime, 'goal', JSON.stringify(route))
        assert.equal(route.shape, 'open', 'Whole-battle benchmark must enter the battle executor')
        task = await evaluate(`__companionHostSmoke.request({type:'agent.companion.control.start',ticketId:${JSON.stringify(route.ticketId)}})`)
      }
      assert.equal(typeof task?.id, 'string', 'Host must return a real task ID')
    } catch (error) {
      startError = String(error)
    }
    mark('benchmark-started', { runId, taskId: task?.id, startedAt, checkpointSha256, startError })
    let endedAt, state
    // Export the rolling task events before their bounded in-memory history can be pruned.
    const taskEvents = new Map()
    const deadline = startedAt + 180000
    let nextLogAt = Date.now() + 30000
    let timedOut = false
    while (!startError) {
      state = await evaluate('__companionHostSmoke.status()')
      const current = state.tasks.find((item) => item.id === task.id)
      for (const event of current?.events ?? []) taskEvents.set(event.seq, event)
      if (['completed', 'failed', 'stopped', 'waiting_user', 'interrupted'].includes(current?.state)) {
        endedAt = Date.now()
        break
      }
      if (Date.now() >= deadline) {
        timedOut = true
        endedAt = Date.now()
        await evaluate(`__companionHostSmoke.request({type:'agent.task.stop',taskId:${JSON.stringify(task.id)}})`)
        break
      }
      if (Date.now() >= nextLogAt) {
        console.log(`Benchmark ${runId}: ${Math.round((Date.now() - startedAt) / 1000)}s, task=${current?.state}`)
        nextLogAt = Date.now() + 30000
      }
      await delay(250)
    }
    endedAt ??= Date.now()
    const final = await save(`benchmark-${runId}-after`)
    const current = task?.id ? final.tasks.find((item) => item.id === task.id) : undefined
    for (const event of current?.events ?? []) taskEvents.set(event.seq, event)
    const events = [...taskEvents.values()].sort((a, b) => a.seq - b.seq)
    await fs.writeFile(path.join(output, `benchmark-${runId}-events.json`), JSON.stringify(events, null, 2) + '\n')
    const trace = final.engine.trace.slice(traceStart)
    const outcome = trace.find((event) => event.kind === 'fact' && event.data.kind === 'battle_result')
    const model = events.filter((event) => event.type === 'model.completed')
    const diagnostics = events.map((event) => event.data?.diagnostic).filter(Boolean)
    const sample = {
      runId,
      mode,
      taskId: task?.id,
      route,
      startError,
      checkpointSha256,
      prompt,
      startedAt,
      endedAt,
      elapsedMs: endedAt - startedAt,
      resultMs: outcome ? outcome.at - startedAt : null,
      taskState: current?.state ?? 'not_started',
      timedOut,
      outcome: outcome?.data.outcome ?? 'unknown',
      inputCount: trace.filter((event) => event.kind === 'input' && !event.data.trusted).length,
      modelRequests: events.filter((event) => event.type === 'model.requested').length,
      // Companion route / initial intent requests precede task creation; service trace supplies their timings.
      taskModelMs: model.map((event) => event.data?.durationMs ?? event.data?.metrics?.totalMs ?? null),
      localSelectionMs: diagnostics.filter((event) => event.phase === 'selection').map((event) => event.durationMs),
      navigationMs: diagnostics.filter((event) => event.phase === 'navigation').map((event) => event.durationMs),
      engineWaitMs: diagnostics.filter((event) => event.phase === 'engine_wait').map((event) => event.durationMs),
      party: final.state.party,
      comparisonEligible: current?.state === 'completed' && outcome?.data.outcome === 'win' && !timedOut,
      unmeasured: ['chat latency (no chat requested)', 'legacy-only queue / context breakdown', 'pure GPU compute time'],
    }
    attempts.push(sample)
    await fs.writeFile(path.join(output, 'benchmark-summary.json'), JSON.stringify({ checkpointSha256, order, attempts }, null, 2) + '\n')
    mark('benchmark-finished', { runId, elapsedMs: sample.elapsedMs, taskState: sample.taskState, outcome: sample.outcome, timedOut })
    if (task?.id && !['completed', 'failed', 'stopped', 'interrupted'].includes(current?.state))
      await evaluate(`__companionHostSmoke.request({type:'agent.task.stop',taskId:${JSON.stringify(task.id)}})`)
  }
  mark('same-save-benchmark-recorded')
}
